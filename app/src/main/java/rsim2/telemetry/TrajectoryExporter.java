    public static String toArduinoHeader(MotionSequence sequence, List<Joint> joints, int sampleRateHz) {
        if (sequence == null) return "// No sequence loaded\n";

        float duration = sequence.getDurationSeconds();
        int totalFrames = Math.max(2, (int) (duration * sampleRateHz));
        float dt = duration / (float) (totalFrames - 1);

        Set<String> jointNamesSet = new LinkedHashSet<>();
        for (Keyframe kf : sequence.getKeyframes()) {
            jointNamesSet.addAll(kf.getJointAnglesDegrees().keySet());
        }
        List<String> jointNames = new ArrayList<>(jointNamesSet);
        Collections.sort(jointNames);
        if (jointNames.isEmpty()) {
            return "// Sequence contains no joint angles\n";
        }

        Map<String, Joint> jointMap = new HashMap<>();
        if (joints != null) {
            for (Joint j : joints) {
                if (j != null && j.getId() != null) {
                    jointMap.put(j.getId(), j);
                }
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("// ==========================================================\n");
        sb.append("// Generated by RSim2 Sim-to-Real Trajectory Exporter\n");
        sb.append("// Sequence: ").append(sequence.getName()).append("\n");
        sb.append("// Duration: ").append(duration).append("s, Sample Rate: ").append(sampleRateHz).append(" Hz\n");
        sb.append("// ==========================================================\n\n");
        sb.append("#pragma once\n");
        sb.append("#include <Arduino.h>\n\n");

        sb.append("#define TRAJECTORY_FRAMES ").append(totalFrames).append("\n");
        sb.append("#define TRAJECTORY_JOINTS ").append(jointNames.size()).append("\n");
        sb.append("#define TRAJECTORY_DT_MS ").append(Math.round(dt * 1000)).append("\n\n");

        sb.append("// Hardware Pin & Calibration Mapping:\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String name = jointNames.get(i);
            String safeMacro = name.replaceAll("[^a-zA-Z0-9_]", "_").toUpperCase(Locale.ROOT);
            Joint j = jointMap.get(name);
            int pin = (j != null && j.getPin() > 0) ? j.getPin() : (9 + i);
            boolean inv = (j != null && j.isInverted());
            float offset = (j != null) ? j.getZeroOffsetDeg() : 0.0f;

            sb.append("#define PIN_").append(safeMacro).append(" ").append(pin).append("\n");
            sb.append("#define INVERT_").append(safeMacro).append(" ").append(inv ? 1 : 0).append("\n");
            sb.append("#define OFFSET_").append(safeMacro).append(" ").append(String.format(Locale.US, "%.1ff", offset)).append("\n");
        }
        sb.append("\n");

        sb.append("// Joint Index Mapping:\n");
        for (int i = 0; i < jointNames.size(); i++) {
            sb.append("// [").append(i).append("] -> ").append(jointNames.get(i)).append("\n");
        }
        sb.append("\n");

        sb.append("const float PROGMEM TRAJECTORY_DATA[TRAJECTORY_FRAMES][TRAJECTORY_JOINTS] = {\n");

        Map<String, Float> sampled = new HashMap<>();
        for (int f = 0; f < totalFrames; f++) {
            float t = f * dt;
            sequence.sample(t, sampled);

            sb.append("    { ");
            for (int j = 0; j < jointNames.size(); j++) {
                String name = jointNames.get(j);
                float deg = sampled.getOrDefault(name, 0.0f);
                sb.append(String.format(Locale.US, "%.2ff", deg));
                if (j < jointNames.size() - 1) sb.append(", ");
            }
            sb.append(" }");
            if (f < totalFrames - 1) sb.append(",");
            sb.append(" // t = ").append(String.format(Locale.US, "%.3fs", t)).append("\n");
        }

        sb.append("};\n");
        return sb.toString();
    }

    public static String toArduinoSketch(MotionSequence sequence, List<Joint> joints, int sampleRateHz) {
        if (sequence == null) return "// No sequence loaded\n";

        float duration = sequence.getDurationSeconds();
        int totalFrames = Math.max(2, (int) (duration * sampleRateHz));
        float dt = duration / (float) (totalFrames - 1);

        Set<String> jointNamesSet = new LinkedHashSet<>();
        for (Keyframe kf : sequence.getKeyframes()) {
            jointNamesSet.addAll(kf.getJointAnglesDegrees().keySet());
        }
        List<String> jointNames = new ArrayList<>(jointNamesSet);
        Collections.sort(jointNames);
        if (jointNames.isEmpty()) {
            return "// Sequence contains no joint angles\n";
        }

        Map<String, Joint> jointMap = new HashMap<>();
        if (joints != null) {
            for (Joint j : joints) {
                if (j != null && j.getId() != null) {
                    jointMap.put(j.getId(), j);
                }
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("// ==========================================================\n");
        sb.append("// RSim2 Sim-to-Real Standalone Arduino Sketch (.ino)\n");
        sb.append("// Sequence: ").append(sequence.getName()).append("\n");
        sb.append("// Total Joints: ").append(jointNames.size()).append(", Duration: ").append(duration).append("s\n");
        sb.append("// Zero-Code Auto-Generated from RSim2 Visual Studio\n");
        sb.append("// ==========================================================\n\n");
        sb.append("#include <Arduino.h>\n");
        sb.append("#include <Servo.h>\n\n");

        sb.append("#define TRAJECTORY_FRAMES ").append(totalFrames).append("\n");
        sb.append("#define TRAJECTORY_JOINTS ").append(jointNames.size()).append("\n");
        sb.append("#define TRAJECTORY_DT_MS  ").append(Math.round(dt * 1000)).append("\n\n");

        sb.append("// Hardware Pin & Calibration Mapping (From Inspector):\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String name = jointNames.get(i);
            String safeMacro = name.replaceAll("[^a-zA-Z0-9_]", "_").toUpperCase(Locale.ROOT);
            Joint j = jointMap.get(name);
            int pin = (j != null && j.getPin() > 0) ? j.getPin() : (9 + i);
            boolean inv = (j != null && j.isInverted());
            float offset = (j != null) ? j.getZeroOffsetDeg() : 0.0f;

            sb.append("#define PIN_").append(safeMacro).append(" ").append(pin).append("\n");
            sb.append("#define INVERT_").append(safeMacro).append(" ").append(inv ? 1 : 0).append("\n");
            sb.append("#define OFFSET_").append(safeMacro).append(" ").append(String.format(Locale.US, "%.1ff", offset)).append("\n");
        }
        sb.append("\n");

        sb.append("const int SERVO_PINS[TRAJECTORY_JOINTS] = {\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String safeMacro = jointNames.get(i).replaceAll("[^a-zA-Z0-9_]", "_").toUpperCase(Locale.ROOT);
            sb.append("    PIN_").append(safeMacro);
            if (i < jointNames.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("};\n\n");

        sb.append("const bool SERVO_INVERT[TRAJECTORY_JOINTS] = {\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String safeMacro = jointNames.get(i).replaceAll("[^a-zA-Z0-9_]", "_").toUpperCase(Locale.ROOT);
            sb.append("    INVERT_").append(safeMacro);
            if (i < jointNames.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("};\n\n");

        sb.append("const float SERVO_OFFSET[TRAJECTORY_JOINTS] = {\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String safeMacro = jointNames.get(i).replaceAll("[^a-zA-Z0-9_]", "_").toUpperCase(Locale.ROOT);
            sb.append("    OFFSET_").append(safeMacro);
            if (i < jointNames.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("};\n\n");

        sb.append("Servo servos[TRAJECTORY_JOINTS];\n\n");

        sb.append("const float PROGMEM TRAJECTORY_DATA[TRAJECTORY_FRAMES][TRAJECTORY_JOINTS] = {\n");
        Map<String, Float> sampled = new HashMap<>();
        for (int f = 0; f < totalFrames; f++) {
            float t = f * dt;
            sequence.sample(t, sampled);

            sb.append("    { ");
            for (int j = 0; j < jointNames.size(); j++) {
                String name = jointNames.get(j);
                float deg = sampled.getOrDefault(name, 0.0f);
                sb.append(String.format(Locale.US, "%.2ff", deg));
                if (j < jointNames.size() - 1) sb.append(", ");
            }
            sb.append(" }");
            if (f < totalFrames - 1) sb.append(",");
            sb.append(" // t = ").append(String.format(Locale.US, "%.3fs", t)).append("\n");
        }
        sb.append("};\n\n");

        sb.append("void setup() {\n");
        sb.append("    Serial.begin(115200);\n");
        sb.append("    Serial.println(F(\"RSim2 Trajectory Player Starting...\"));\n\n");
        sb.append("    for (int j = 0; j < TRAJECTORY_JOINTS; j++) {\n");
        sb.append("        servos[j].attach(SERVO_PINS[j]);\n");
        sb.append("        float initialAngle = pgm_read_float(&TRAJECTORY_DATA[0][j]);\n");
        sb.append("        if (SERVO_INVERT[j]) initialAngle = 180.0f - initialAngle;\n");
        sb.append("        initialAngle += SERVO_OFFSET[j];\n");
        sb.append("        servos[j].write((int) constrain(round(initialAngle), 0, 180));\n");
        sb.append("    }\n");
        sb.append("    delay(1000); // Wait for servos to reach initial position\n");
        sb.append("}\n\n");

        sb.append("void loop() {\n");
        sb.append("    for (int frame = 0; frame < TRAJECTORY_FRAMES; frame++) {\n");
        sb.append("        for (int j = 0; j < TRAJECTORY_JOINTS; j++) {\n");
        sb.append("            float rawAngle = pgm_read_float(&TRAJECTORY_DATA[frame][j]);\n");
        sb.append("            if (SERVO_INVERT[j]) {\n");
        sb.append("                rawAngle = 180.0f - rawAngle;\n");
        sb.append("            }\n");
        sb.append("            rawAngle += SERVO_OFFSET[j];\n");
        sb.append("            int cmd = (int) constrain(round(rawAngle), 0, 180);\n");
        sb.append("            servos[j].write(cmd);\n");
        sb.append("        }\n");
        sb.append("        delay(TRAJECTORY_DT_MS);\n");
        sb.append("    }\n");
        sb.append("    delay(2000); // Pause before repeating sequence\n");
        sb.append("}\n");

        return sb.toString();
    }

    public static String toCsv(MotionSequence sequence, int sampleRateHz) {
        if (sequence == null) return "time\n";

        float duration = sequence.getDurationSeconds();
        int totalFrames = Math.max(2, (int) (duration * sampleRateHz));
        float dt = duration / (float) (totalFrames - 1);

        Set<String> jointNamesSet = new LinkedHashSet<>();
        for (Keyframe kf : sequence.getKeyframes()) {
            jointNamesSet.addAll(kf.getJointAnglesDegrees().keySet());
        }
        List<String> jointNames = new ArrayList<>(jointNamesSet);
        Collections.sort(jointNames);

        StringBuilder sb = new StringBuilder();
        sb.append("time_sec");
        for (String name : jointNames) {
            sb.append(",").append(name);
        }
        sb.append("\n");

        Map<String, Float> sampled = new HashMap<>();
        for (int f = 0; f < totalFrames; f++) {
            float t = f * dt;
            sequence.sample(t, sampled);

            sb.append(String.format(Locale.US, "%.4f", t));
            for (String name : jointNames) {
                float deg = sampled.getOrDefault(name, 0.0f);
                sb.append(String.format(Locale.US, ",%.2f", deg));
            }
            sb.append("\n");
        }

        return sb.toString();
    }

    public static String toPythonScript(MotionSequence sequence, List<Joint> joints, int sampleRateHz) {
        if (sequence == null) return "# No sequence loaded\n";

        float duration = sequence.getDurationSeconds();
        int totalFrames = Math.max(2, (int) (duration * sampleRateHz));
        float dt = duration / (float) (totalFrames - 1);

        Set<String> jointNamesSet = new LinkedHashSet<>();
        for (Keyframe kf : sequence.getKeyframes()) {
            jointNamesSet.addAll(kf.getJointAnglesDegrees().keySet());
        }
        List<String> jointNames = new ArrayList<>(jointNamesSet);
        Collections.sort(jointNames);
        if (jointNames.isEmpty()) {
            return "# Sequence contains no joint angles\n";
        }

        Map<String, Joint> jointMap = new HashMap<>();
        if (joints != null) {
            for (Joint j : joints) {
                if (j != null && j.getId() != null) {
                    jointMap.put(j.getId(), j);
                }
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("#!/usr/bin/env python3\n");
        sb.append("# ==========================================================\n");
        sb.append("# RSim2 Sim-to-Real Standalone Raspberry Pi Python Controller\n");
        sb.append("# Sequence: ").append(sequence.getName()).append("\n");
        sb.append("# Duration: ").append(duration).append("s, Sample Rate: ").append(sampleRateHz).append(" Hz\n");
        sb.append("# Zero-Code Auto-Generated from RSim2 Visual Studio\n");
        sb.append("# ==========================================================\n\n");
        sb.append("import time\n");
        sb.append("import sys\n\n");

        sb.append("# Set to True if using I2C PCA9685 16-channel servo board (adafruit-circuitpython-servokit)\n");
        sb.append("# Set to False if using direct Raspberry Pi GPIO pins (gpiozero)\n");
        sb.append("USE_PCA9685 = False\n\n");

        sb.append("# Hardware Pin & Calibration Mapping:\n");
        sb.append("JOINTS_CONFIG = {\n");
        for (int i = 0; i < jointNames.size(); i++) {
            String name = jointNames.get(i);
            Joint j = jointMap.get(name);
            int pin = (j != null && j.getPin() > 0) ? j.getPin() : (18 + i);
            boolean inv = (j != null && j.isInverted());
            float offset = (j != null) ? j.getZeroOffsetDeg() : 0.0f;

            sb.append("    \"").append(name).append("\": {")
              .append("\"pin\": ").append(pin).append(", ")
              .append("\"invert\": ").append(inv ? "True" : "False").append(", ")
              .append("\"offset\": ").append(String.format(Locale.US, "%.1f", offset))
              .append("}");
            if (i < jointNames.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("}\n\n");

        sb.append("TRAJECTORY_DT_SEC = ").append(String.format(Locale.US, "%.4f", dt)).append("\n");
        sb.append("TRAJECTORY_FRAMES = [\n");

        Map<String, Float> sampled = new HashMap<>();
        for (int f = 0; f < totalFrames; f++) {
            float t = f * dt;
            sequence.sample(t, sampled);

            sb.append("    {");
            for (int j = 0; j < jointNames.size(); j++) {
                String name = jointNames.get(j);
                float deg = sampled.getOrDefault(name, 0.0f);
                sb.append("\"").append(name).append("\": ").append(String.format(Locale.US, "%.2f", deg));
                if (j < jointNames.size() - 1) sb.append(", ");
            }
            sb.append("}");
            if (f < totalFrames - 1) sb.append(",");
            sb.append("  # t = ").append(String.format(Locale.US, "%.3fs", t)).append("\n");
        }
        sb.append("]\n\n");

        sb.append("servos = {}\n\n");
        sb.append("def setup_servos():\n");
        sb.append("    global servos\n");
        sb.append("    if USE_PCA9685:\n");
        sb.append("        try:\n");
        sb.append("            from adafruit_servokit import ServoKit\n");
        sb.append("            kit = ServoKit(channels=16)\n");
        sb.append("            for name, cfg in JOINTS_CONFIG.items():\n");
        sb.append("                servos[name] = kit.servo[cfg[\"pin\"]]\n");
        sb.append("            print(\"[INFO] PCA9685 I2C ServoKit initialized.\")\n");
        sb.append("        except ImportError:\n");
        sb.append("            print(\"[ERROR] adafruit-circuitpython-servokit not installed!\")\n");
        sb.append("            print(\"Run: pip3 install adafruit-circuitpython-servokit\")\n");
        sb.append("            sys.exit(1)\n");
        sb.append("    else:\n");
        sb.append("        try:\n");
        sb.append("            from gpiozero import AngularServo\n");
        sb.append("            for name, cfg in JOINTS_CONFIG.items():\n");
        sb.append("                servos[name] = AngularServo(cfg[\"pin\"], min_angle=0, max_angle=180)\n");
        sb.append("            print(\"[INFO] Direct Raspberry Pi GPIO servos initialized via gpiozero.\")\n");
        sb.append("        except ImportError:\n");
        sb.append("            print(\"[ERROR] gpiozero not installed!\")\n");
        sb.append("            print(\"Run: pip3 install gpiozero\")\n");
        sb.append("            sys.exit(1)\n\n");

        sb.append("def write_angle(joint_name, raw_angle_deg):\n");
        sb.append("    if joint_name not in servos or joint_name not in JOINTS_CONFIG:\n");
        sb.append("        return\n");
        sb.append("    cfg = JOINTS_CONFIG[joint_name]\n");
        sb.append("    angle = 180.0 - raw_angle_deg if cfg[\"invert\"] else raw_angle_deg\n");
        sb.append("    angle += cfg[\"offset\"]\n");
        sb.append("    clamped = max(0.0, min(180.0, angle))\n");
        sb.append("    if USE_PCA9685:\n");
        sb.append("        servos[joint_name].angle = clamped\n");
        sb.append("    else:\n");
        sb.append("        servos[joint_name].angle = clamped\n\n");

        sb.append("def main():\n");
        sb.append("    print(\"[START] RSim2 Raspberry Pi Trajectory Player Started.\")\n");
        sb.append("    setup_servos()\n");
        sb.append("    # Move to initial pose\n");
        sb.append("    if len(TRAJECTORY_FRAMES) > 0:\n");
        sb.append("        for name, val in TRAJECTORY_FRAMES[0].items():\n");
        sb.append("            write_angle(name, val)\n");
        sb.append("        time.sleep(1.0)\n\n");
        sb.append("    try:\n");
        sb.append("        while True:\n");
        sb.append("            for frame in TRAJECTORY_FRAMES:\n");
        sb.append("                t_start = time.time()\n");
        sb.append("                for name, val in frame.items():\n");
        sb.append("                    write_angle(name, val)\n");
        sb.append("                elapsed = time.time() - t_start\n");
        sb.append("                sleep_time = max(0.0, TRAJECTORY_DT_SEC - elapsed)\n");
        sb.append("                time.sleep(sleep_time)\n");
        sb.append("            time.sleep(1.5)  # Pause before loop repeat\n");
        sb.append("    except KeyboardInterrupt:\n");
        sb.append("        print(\"\\n[STOP] Motion playback interrupted safely by user.\")\n\n");

        sb.append("if __name__ == \"__main__\":\n");
        sb.append("    main()\n");

        return sb.toString();
    }

    public static String toRpiLiveReceiverScript() {
        return "#!/usr/bin/env python3\n" +
               "# ==========================================================\n" +
               "# RSim2 Raspberry Pi Live UDP Receiver Daemon\n" +
               "# Listens to real-time motion streamed from RSim2 over Wi-Fi/Ethernet\n" +
               "# ==========================================================\n\n" +
               "import socket\n" +
               "import json\n" +
               "import sys\n\n" +
               "UDP_HOST = \"0.0.0.0\"  # Listen on all local interfaces\n" +
               "UDP_PORT = 8888\n" +
               "USE_PCA9685 = False  # Set to True if using I2C PCA9685 Hat\n\n" +
               "# Map joint names to GPIO pins or PCA9685 channels:\n" +
               "PIN_MAPPING = {\n" +
               "    \"joint_1\": 18,\n" +
               "    \"joint_2\": 19,\n" +
               "    \"joint_3\": 20,\n" +
               "    \"joint_4\": 21\n" +
               "}\n\n" +
               "servos = {}\n\n" +
               "def init_hardware():\n" +
               "    global servos\n" +
               "    if USE_PCA9685:\n" +
               "        try:\n" +
               "            from adafruit_servokit import ServoKit\n" +
               "            kit = ServoKit(channels=16)\n" +
               "            for name, pin in PIN_MAPPING.items():\n" +
               "                servos[name] = kit.servo[pin]\n" +
               "            print(f\"[INFO] PCA9685 initialized for {len(servos)} joints.\")\n" +
               "        except ImportError:\n" +
               "            print(\"[ERROR] adafruit-circuitpython-servokit not installed!\")\n" +
               "            sys.exit(1)\n" +
               "    else:\n" +
               "        try:\n" +
               "            from gpiozero import AngularServo\n" +
               "            for name, pin in PIN_MAPPING.items():\n" +
               "                servos[name] = AngularServo(pin, min_angle=0, max_angle=180)\n" +
               "            print(f\"[INFO] gpiozero initialized for {len(servos)} joints.\")\n" +
               "        except ImportError:\n" +
               "            print(\"[ERROR] gpiozero not installed!\")\n" +
               "            sys.exit(1)\n\n" +
               "def main():\n" +
               "    init_hardware()\n" +
               "    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)\n" +
               "    sock.bind((UDP_HOST, UDP_PORT))\n" +
               "    print(f\"[READY] RSim2 Live Receiver listening on port {UDP_PORT}...\")\n\n" +
               "    try:\n" +
               "        while True:\n" +
               "            data, addr = sock.recvfrom(4096)\n" +
               "            try:\n" +
               "                payload = json.loads(data.decode('utf-8').strip())\n" +
               "                msg_type = payload.get(\"type\")\n" +
               "                if msg_type == \"estop\":\n" +
               "                    print(\"[WARNING] EMERGENCY STOP RECEIVED FROM RSIM2!\")\n" +
               "                elif msg_type == \"cmd\":\n" +
               "                    joints = payload.get(\"joints\", {})\n" +
               "                    for name, deg in joints.items():\n" +
               "                        if name in servos:\n" +
               "                            angle = max(0.0, min(180.0, float(deg)))\n" +
               "                            servos[name].angle = angle\n" +
               "            except Exception as e:\n" +
               "                pass\n" +
               "    except KeyboardInterrupt:\n" +
               "        print(\"\\n[STOP] Receiver shutting down.\")\n" +
               "    finally:\n" +
               "        sock.close()\n\n" +
               "if __name__ == \"__main__\":\n" +
               "    main()\n";
    }

    public static boolean saveToFile(String content, String filePath) {
        try {
            File file = new File(filePath);
            File parent = file.getParentFile();
            if (parent != null && !parent.exists()) {
                parent.mkdirs();
            }
            try (java.io.OutputStreamWriter writer = new java.io.OutputStreamWriter(
                    new java.io.FileOutputStream(file), java.nio.charset.StandardCharsets.UTF_8)) {
                writer.write(content);
            }
            return true;
        } catch (IOException e) {
            e.printStackTrace();
            return false;
        }
    }
